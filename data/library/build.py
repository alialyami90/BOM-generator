"""Build the shipped psa-devices library from the example library and the device database.

The shipped library is examples/library.yaml with each original part's datasheet inrush
and input voltage range from data/device-db added (plan Q38), and its make as the device
database records it, followed by the parts in data/library/additions.yaml. The example
library leaves them out so the golden values stay those of the spec's example workbook.

Usage, from the repository root: ``python data/library/build.py``. It rewrites
data/library/psa-devices.yaml; tests/unit/test_shipped_library.py fails while the file
is out of date.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

from bomgen.io.round_trip import dump_text, load_text

ROOT = Path(__file__).resolve().parents[2]
EXAMPLE = ROOT / "examples" / "library.yaml"
ADDITIONS = ROOT / "data" / "library" / "additions.yaml"
DEVICE_DB = ROOT / "data" / "device-db"
SHIPPED = ROOT / "data" / "library" / "psa-devices.yaml"

DATASHEET_KEYS = ("inrush_a", "inrush_ms", "input_v_min", "input_v_max")
HEADER = """\
# yaml-language-server: $schema=../../schemas/library.schema.json
#
# GENERATED by data/library/build.py: do not edit. Change examples/library.yaml or
# data/device-db/ and run `python data/library/build.py` again.
#
# The shipped psa-devices library: examples/library.yaml plus each original part's
# datasheet inrush and input voltage range from data/device-db/ (plan Q38), and its make
# as the device database records it, then the parts in data/library/additions.yaml.
"""


def datasheets(device_db: Path = DEVICE_DB) -> dict[str, dict[str, Any]]:
    """Each original part's datasheet figures and make that the library carries, by part id."""
    found: dict[str, dict[str, Any]] = {}
    for path in sorted(device_db.glob("*.yaml")):
        for record in yaml.safe_load(path.read_text(encoding="utf-8"))["records"]:
            datasheet = record.get("datasheet") or {}
            figures = {k: datasheet[k] for k in DATASHEET_KEYS if datasheet.get(k) is not None}
            if record.get("make"):
                figures["make"] = record["make"]
            if figures:
                found[record["part_id"]] = figures
    return found


def build(example: str, figures: dict[str, dict[str, Any]], additions: str) -> str:
    """The shipped library's text: ``example`` with ``figures`` added to its originals and
    the ``additions`` file's devices appended."""
    data = load_text(example)
    for device in data["devices"]:
        if device.get("tier") is not None or device["part_id"] not in figures:
            continue
        keys = list(device)
        at = keys.index("alt_group") + 1 if "alt_group" in keys else len(keys)
        added = {k: v for k, v in figures[device["part_id"]].items() if k != "make"}
        if "make" in figures[device["part_id"]]:
            device["make"] = figures[device["part_id"]]["make"]
        for offset, (key, value) in enumerate(added.items()):
            if key in device:
                raise ValueError(f"{device['part_id']} already has {key} in the example")
            device.insert(at + offset, key, value)
            if offset == 0:
                device.yaml_add_eol_comment("datasheet (data/device-db)", key)
    data["devices"].extend(load_text(additions)["devices"])
    text = dump_text(data)
    body = text.split("\n", 1)[1] if text.startswith("# yaml-language-server") else text
    lines = body.splitlines(keepends=True)
    while lines and lines[0].startswith("#"):
        lines.pop(0)  # the example's own header describes the example workbook
    return HEADER + "".join(lines)


def main() -> None:
    text = build(
        EXAMPLE.read_text(encoding="utf-8"),
        datasheets(),
        ADDITIONS.read_text(encoding="utf-8"),
    )
    SHIPPED.write_text(text, encoding="utf-8")
    print(f"wrote {SHIPPED.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
