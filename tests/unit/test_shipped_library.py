"""The shipped psa-devices library in data/library/ (plan Q38).

It is the example library plus each original part's datasheet inrush and input range
from data/device-db/, generated by data/library/build.py.
"""

import importlib.util
import shutil
from pathlib import Path
from types import ModuleType

import pytest
import yaml

from bomgen.build import build_substation
from bomgen.io.loader import load_library, load_substation
from bomgen.models.library import Library

REPO = Path(__file__).resolve().parents[2]
SHIPPED = REPO / "data" / "library" / "psa-devices.yaml"
EXAMPLE = REPO / "examples" / "library.yaml"


def _build_module() -> ModuleType:
    spec = importlib.util.spec_from_file_location("shipped_build", SHIPPED.parent / "build.py")
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def shipped() -> Library:
    return load_library(SHIPPED)


def test_the_shipped_library_is_up_to_date_with_its_sources() -> None:
    build = _build_module()

    expected = build.build(EXAMPLE.read_text(encoding="utf-8"), build.datasheets())

    assert SHIPPED.read_text(encoding="utf-8") == expected, (
        "data/library/psa-devices.yaml is out of date: run `python data/library/build.py`"
    )


def test_the_shipped_library_is_the_example_plus_the_originals_datasheet_figures(
    shipped: Library,
) -> None:
    example = load_library(EXAMPLE)
    keys = {"inrush_a", "inrush_ms", "input_v_min", "input_v_max"}

    assert shipped.part_ids() == example.part_ids()
    assert shipped.catalogues == example.catalogues
    assert shipped.catalogue_brands == example.catalogue_brands
    for ours, theirs in zip(shipped.devices, example.devices, strict=True):
        assert ours.model_dump(exclude=keys) == theirs.model_dump(exclude=keys), ours.part_id
        if ours.tier is not None:
            assert ours == theirs, ours.part_id


def test_the_originals_carry_their_datasheet_inrush_and_input_range(shipped: Library) -> None:
    db = {
        r["part_id"]: r
        for p in (REPO / "data" / "device-db").glob("*.yaml")
        for r in yaml.safe_load(p.read_text(encoding="utf-8"))["records"]
    }

    rtac = shipped.get("SEL-3555-RTAC")
    fgr = shipped.get("FGR-60F")
    assert rtac is not None
    assert fgr is not None
    assert rtac.inrush_a == db["SEL-3555-RTAC"]["datasheet"]["inrush_a"]
    assert (fgr.input_v_min, fgr.input_v_max) == (12, 125)


def test_the_example_project_builds_with_the_shipped_library(tmp_path: Path) -> None:
    # The example project's own folder, with the shipped library in place of its copy.
    # MCB sizes may differ from the goldens: the inrush figures are datasheet data.
    project = tmp_path / "examples"
    shutil.copytree(REPO / "examples", project)
    shutil.copyfile(SHIPPED, project / "library.yaml")
    loaded = load_substation(project / "substations" / "gis01" / "substation.yaml")

    outcome = build_substation(loaded, tmp_path / "bom.xlsx")

    assert outcome.result is not None
    assert outcome.failed is False
    assert outcome.path is not None
    assert outcome.path.is_file()
