def _contradictions(part: DeviceType, original: DeviceType) -> list[str]:
    """What an alternative's description states that its own data contradicts."""
    text = part.description_template
    found = []
    for count, media in re.findall(r"(\d+) (MM|SM|RJ45|SFP)\b", text):
        if media == "SFP":
            has = sum(p.count for p in part.ports if p.kind == "sfp_slot")
            if int(count) > has:
                found.append(f"{count} SFP, has {has}")
        elif int(count) != sum(p.count for p in part.ports if p.media == media):
            found.append(f"{count} {media}")
    for watts in re.findall(r"(\d+(?:\.\d+)?) ?W\b", text):
        if float(watts) != part.unit_power_w:
            found.append(f"{watts} W, has {part.unit_power_w}")
    if part.supply_type in ("VDC", "VAC"):
        for volts, kind in re.findall(r"(\d+) ?V ?(AC|DC)\b", text):
            if (int(volts), "V" + kind) != (part.voltage_v, part.supply_type):
                found.append(f"{volts} V {kind}")
    for inputs in re.findall(r"(\d+) ?DI\b", text):
        if int(inputs) != part.di_inputs:
            found.append(f"{inputs} DI, has {part.di_inputs}")
    for cable in re.findall(r"LMR-\d+", text):
        if cable not in (part.model or ""):
            found.append(cable)
    if original.make and original.make != part.make and original.make in text:
        found.append(f"names {original.make}")
    return found


def test_m43_no_alternative_description_contradicts_its_own_data(shipped: Library) -> None:
    by_id = {d.part_id: d for d in shipped.devices}

    wrong = {
        d.part_id: found
        for d in shipped.devices
        if d.tier and d.alt_group and (found := _contradictions(d, by_id[d.alt_group]))
    }

    assert wrong == {}
